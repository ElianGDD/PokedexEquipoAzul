package com.RisosuIT.Pokedex.DAO;

class Move_Learn_Method {

    private String egg;
    private String url;

    public Move_Learn_Method() {
    }

    public Move_Learn_Method(String egg, String url) {
        this.egg = egg;
        this.url = url;
    }

    public String getEgg() {
        return egg;
    }

    public void setEgg(String egg) {
        this.egg = egg;
    }

    public String getUrl() {
        return url;
    }

    public void setUrl(String url) {
        this.url = url;
    }

}
